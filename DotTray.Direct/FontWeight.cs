namespace DotTray.Direct;

/// <summary>
/// Represents the weight of a font
/// </summary>
public enum FontWeight
{
    /// <summary>Light</summary>
    Light = 300,

    /// <summary>Normal</summary>
    Normal = 400,

    /// <summary>Medium</summary>
    Medium = 500,

    /// <summary>Semi bold</summary>
    SemiBold = 600,

    /// <summary>Bold</summary>
    Bold = 700
}